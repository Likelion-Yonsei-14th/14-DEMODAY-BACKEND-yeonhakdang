CREATE TABLE purchase_order (
 id UUID PRIMARY KEY, member_id UUID NOT NULL REFERENCES member_account(id),
 result_id UUID REFERENCES analysis_result(id) ON DELETE SET NULL,
 product_code VARCHAR(20) NOT NULL REFERENCES product(code),
 amount INTEGER NOT NULL, currency VARCHAR(8) NOT NULL DEFAULT 'KRW',
 status VARCHAR(30) NOT NULL, payment_id VARCHAR(80) NOT NULL UNIQUE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, paid_at TIMESTAMP WITH TIME ZONE,
 consent_version VARCHAR(80) NOT NULL, consent_at TIMESTAMP WITH TIME ZONE NOT NULL,
 universities TEXT, relation VARCHAR(20),
 idempotency_key VARCHAR(80) NOT NULL, request_fingerprint VARCHAR(64) NOT NULL,
 UNIQUE(member_id,idempotency_key)
);
CREATE TABLE entitlement (
 order_id UUID NOT NULL REFERENCES purchase_order(id), product_code VARCHAR(20) NOT NULL REFERENCES product(code),
 status VARCHAR(20) NOT NULL, first_viewed_at TIMESTAMP WITH TIME ZONE,
 content TEXT, content_version VARCHAR(80), rerolls INTEGER NOT NULL DEFAULT 0,
 PRIMARY KEY(order_id,product_code)
);
CREATE TABLE refund_request (
 id UUID PRIMARY KEY, order_id UUID NOT NULL REFERENCES purchase_order(id),
 reason VARCHAR(40) NOT NULL, status VARCHAR(30) NOT NULL, amount INTEGER NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, reviewed_at TIMESTAMP WITH TIME ZONE,
 reviewed_by UUID REFERENCES member_account(id), cancellation_id VARCHAR(120) UNIQUE,
 baseline_cancelled INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE webhook_receipt (
 id VARCHAR(200) PRIMARY KEY, processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX order_member_idx ON purchase_order(member_id,created_at);
CREATE INDEX refund_order_idx ON refund_request(order_id,created_at);
CREATE INDEX result_member_idx ON analysis_result(member_id);
CREATE INDEX consent_member_idx ON consent(member_id,item,recorded_at);
CREATE TABLE SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY, SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL, LAST_ACCESS_TIME BIGINT NOT NULL, MAX_INACTIVE_INTERVAL INTEGER NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL, PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION(SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION(EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION(PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL, ATTRIBUTE_BYTES BYTEA NOT NULL,
 PRIMARY KEY(SESSION_PRIMARY_ID,ATTRIBUTE_NAME)
);
