CREATE TABLE member_account (
 id UUID PRIMARY KEY, kakao_id VARCHAR(64) UNIQUE, status VARCHAR(20) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'USER', created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 withdrawn_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE consent (
 id UUID PRIMARY KEY, member_id UUID NOT NULL REFERENCES member_account(id),
 item VARCHAR(40) NOT NULL, version VARCHAR(80) NOT NULL, accepted BOOLEAN NOT NULL,
 recorded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE analysis_result (
 id UUID PRIMARY KEY, member_id UUID NOT NULL REFERENCES member_account(id),
 engine_version VARCHAR(80) NOT NULL, summary TEXT NOT NULL,
 provenance VARCHAR(30) NOT NULL DEFAULT 'CLIENT_UNVERIFIED', created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE product (
 code VARCHAR(20) PRIMARY KEY, title VARCHAR(80) NOT NULL, price INTEGER NOT NULL CHECK(price > 0)
);
